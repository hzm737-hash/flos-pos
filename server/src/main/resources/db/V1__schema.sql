-- Flos back office schema. Works on PostgreSQL 13+ and on H2 in PostgreSQL mode (tests).
-- Money is stored in haléře (BIGINT). Stock quantities are stored in thousandths of a unit
-- (qty_milli), so 0.25 kg = 250.  Times are epoch milliseconds.

CREATE TABLE orgs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    ico VARCHAR(20) NOT NULL DEFAULT '',
    dic VARCHAR(20) NOT NULL DEFAULT '',
    vat_payer BOOLEAN NOT NULL DEFAULT FALSE,
    address TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    email VARCHAR(200),
    name VARCHAR(200) NOT NULL,
    role VARCHAR(20) NOT NULL,
    password_hash VARCHAR(300),
    pin_hash VARCHAR(300),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX users_email ON users(email);

CREATE TABLE sessions (
    token_hash VARCHAR(100) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);

CREATE TABLE branches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    name VARCHAR(200) NOT NULL,
    address TEXT NOT NULL DEFAULT '',
    eet_id_jednotky INT,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    branch_id BIGINT NOT NULL REFERENCES branches(id),
    name VARCHAR(200) NOT NULL,
    eet_id_pokl VARCHAR(20) NOT NULL DEFAULT '',
    token_hash VARCHAR(100),
    pairing_code VARCHAR(20),
    pairing_expires_at BIGINT,
    paired_at BIGINT,
    last_seen_at BIGINT,
    app_version VARCHAR(40),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX devices_token ON devices(token_hash);

CREATE TABLE api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    name VARCHAR(200) NOT NULL,
    prefix VARCHAR(20) NOT NULL,
    key_hash VARCHAR(100) NOT NULL,
    scope VARCHAR(20) NOT NULL,
    created_at BIGINT NOT NULL,
    last_used_at BIGINT,
    revoked BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX api_keys_hash ON api_keys(key_hash);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    name VARCHAR(200) NOT NULL,
    color BIGINT NOT NULL DEFAULT 4281236843,
    sort_order INT NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at BIGINT NOT NULL
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    category_id BIGINT REFERENCES categories(id),
    name VARCHAR(200) NOT NULL,
    price BIGINT NOT NULL,
    vat_percent INT NOT NULL DEFAULT 21,
    sku VARCHAR(60) NOT NULL DEFAULT '',
    barcode VARCHAR(60) NOT NULL DEFAULT '',
    unit VARCHAR(10) NOT NULL DEFAULT 'ks',
    cost_price BIGINT NOT NULL DEFAULT 0,
    track_stock BOOLEAN NOT NULL DEFAULT FALSE,
    sellable BOOLEAN NOT NULL DEFAULT TRUE,
    min_stock_milli BIGINT NOT NULL DEFAULT 0,
    sort_order INT NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at BIGINT NOT NULL
);
CREATE INDEX products_org ON products(org_id);

-- A product made of other products (e.g. cappuccino = 18 g coffee + 150 ml milk).
CREATE TABLE recipe_items (
    product_id BIGINT NOT NULL REFERENCES products(id),
    ingredient_id BIGINT NOT NULL REFERENCES products(id),
    qty_milli BIGINT NOT NULL,
    PRIMARY KEY (product_id, ingredient_id)
);

CREATE TABLE stock_levels (
    branch_id BIGINT NOT NULL REFERENCES branches(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    qty_milli BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (branch_id, product_id)
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    branch_id BIGINT NOT NULL REFERENCES branches(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    qty_milli BIGINT NOT NULL,
    kind VARCHAR(20) NOT NULL,
    unit_cost BIGINT,
    note TEXT NOT NULL DEFAULT '',
    ref VARCHAR(60) NOT NULL DEFAULT '',
    user_id BIGINT,
    created_at BIGINT NOT NULL
);
CREATE INDEX stock_movements_branch ON stock_movements(branch_id, created_at);

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    branch_id BIGINT NOT NULL REFERENCES branches(id),
    device_id BIGINT NOT NULL REFERENCES devices(id),
    number VARCHAR(40) NOT NULL,
    created_at BIGINT NOT NULL,
    total BIGINT NOT NULL,
    received BIGINT NOT NULL,
    payment VARCHAR(20) NOT NULL,
    cashier VARCHAR(200) NOT NULL DEFAULT '',
    discount_percent INT NOT NULL DEFAULT 0,
    cancelled BOOLEAN NOT NULL DEFAULT FALSE,
    storno_number VARCHAR(40),
    eet_status VARCHAR(20),
    eet_pok VARCHAR(40),
    uploaded_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX sales_device_number ON sales(device_id, number);
CREATE INDEX sales_org_time ON sales(org_id, created_at);

CREATE TABLE sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sales(id),
    product_id BIGINT,
    name VARCHAR(200) NOT NULL,
    unit_price BIGINT NOT NULL,
    vat_percent INT NOT NULL,
    quantity INT NOT NULL,
    discount_percent INT NOT NULL DEFAULT 0
);
CREATE INDEX sale_items_sale ON sale_items(sale_id);

CREATE TABLE attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    branch_id BIGINT NOT NULL REFERENCES branches(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    clock_in BIGINT NOT NULL,
    clock_out BIGINT,
    device_id BIGINT
);
CREATE INDEX attendance_org ON attendance(org_id, clock_in);
