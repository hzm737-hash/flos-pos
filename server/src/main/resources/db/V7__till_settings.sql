-- Till settings kept in the back office: device_id 0 = the whole company, otherwise one till
CREATE TABLE till_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    device_id BIGINT NOT NULL DEFAULT 0,
    skey VARCHAR(40) NOT NULL,
    svalue TEXT NOT NULL,
    updated_at BIGINT NOT NULL,
    written_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX till_settings_key ON till_settings(org_id, device_id, skey);
CREATE INDEX till_settings_written ON till_settings(org_id, written_at);
-- Which secrets a till has set (names only, comma separated), never their values
ALTER TABLE devices ADD COLUMN secrets_set VARCHAR(400) NOT NULL DEFAULT ''
