-- Ordering from the table (QR code on each table). The secret signs the tables' QR codes. Orders wait
-- here until a till of the company fetches them and accepts or declines them.
ALTER TABLE menus ADD COLUMN table_secret VARCHAR(64);

CREATE TABLE table_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    table_name VARCHAR(40) NOT NULL,
    data TEXT NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'NEW',
    created_at BIGINT NOT NULL,
    fetched_at BIGINT
);
CREATE INDEX table_orders_org ON table_orders(org_id, status);
