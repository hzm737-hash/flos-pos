-- New versions of the till app, uploaded in the back office (or by the build) and offered to the tills
CREATE TABLE app_releases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    platform VARCHAR(20) NOT NULL,
    version_code INT NOT NULL,
    version_name VARCHAR(40) NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    size BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    dl_key VARCHAR(40) NOT NULL,
    data BYTEA NOT NULL,
    -- Ids of the tills that get it, comma separated, empty = all tills
    devices VARCHAR(2000) NOT NULL DEFAULT '',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at BIGINT NOT NULL
);
CREATE INDEX app_releases_org ON app_releases(org_id, platform);
ALTER TABLE devices ADD COLUMN platform VARCHAR(20);
ALTER TABLE devices ADD COLUMN version_code INT
