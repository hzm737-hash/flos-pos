-- Table reservations from the restaurant's website. The customer's contact details are kept apart, so
-- they can be erased after 30 days while the reservation itself stays. at = the booked time (epoch ms).
CREATE TABLE web_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    token VARCHAR(64) NOT NULL,
    data TEXT NOT NULL,
    customer TEXT,
    status VARCHAR(12) NOT NULL DEFAULT 'NEW',
    at BIGINT NOT NULL,
    table_name VARCHAR(40),
    reply TEXT,
    created_at BIGINT NOT NULL,
    fetched_at BIGINT
);
CREATE INDEX web_reservations_org ON web_reservations(org_id, status);
