ALTER TABLE products ADD COLUMN price_lists TEXT NOT NULL DEFAULT '';
ALTER TABLE products ADD COLUMN open_price BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE products ADD COLUMN icon VARCHAR(40) NOT NULL DEFAULT '';
ALTER TABLE products ADD COLUMN image VARCHAR(80) NOT NULL DEFAULT '';
ALTER TABLE categories ADD COLUMN icon VARCHAR(40) NOT NULL DEFAULT '';

CREATE TABLE images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    img_key VARCHAR(40) NOT NULL,
    mime VARCHAR(40) NOT NULL,
    data TEXT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX images_org ON images(org_id);
