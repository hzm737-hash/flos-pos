-- Orders from the restaurant's website (delivery or pick-up). The customer's contact details are kept
-- apart from the order, so they can be erased after 30 days while the order itself stays.
CREATE TABLE web_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES orgs(id),
    token VARCHAR(64) NOT NULL,
    data TEXT NOT NULL,
    customer TEXT,
    status VARCHAR(12) NOT NULL DEFAULT 'NEW',
    ready_at BIGINT,
    created_at BIGINT NOT NULL,
    fetched_at BIGINT
);
CREATE INDEX web_orders_org ON web_orders(org_id, status);
